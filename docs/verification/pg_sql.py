"""PostgreSQL spelling for the generators' SQL.

The generators were written for MySQL and still compose statements with its
session variables ("set @id = last_insert_id();", "(@id, 'fr', ...)"), which
read well. PostgreSQL has no such variables; convert() rewrites them into
set_config()/current_setting(), which hold a value for the rest of the
session the same way. It is the same rewrite that moved the checked-in
migrations to PostgreSQL, so a generator's output still matches its
migration byte for byte.
"""
import re

SET = re.compile(r"^set @(\w+)\s*=\s*(.*?);[ \t]*$", re.M | re.S)


def convert(text: str) -> str:
    types = {}

    def set_var(m):
        name, expr = m.group(1), m.group(2).strip()
        if expr == "last_insert_id()":
            types[name] = "bigint"
            return f"select set_config('app.{name}', lastval()::text, false);"
        types[name] = "text" if expr.startswith("'") else "bigint"
        if types[name] == "text":
            return f"select set_config('app.{name}', {expr}, false);"
        return f"select set_config('app.{name}', ({expr})::text, false);"

    # Assignments first, so their own @refs (e.g. "@st" inside @item's
    # subquery) are rewritten by the reference pass below.
    text = SET.sub(set_var, text)

    out = []
    for line in text.split("\n"):
        if line.lstrip().startswith("--"):
            out.append(line)
            continue

        def ref(m):
            name = m.group(1)
            if name not in types:  # an e-mail address in a string literal
                return m.group(0)
            if types[name] == "text":
                return f"current_setting('app.{name}')"
            return f"current_setting('app.{name}')::bigint"

        line = re.sub(r"@(\w+)", ref, line)
        line = line.replace("bigint primary key auto_increment",
                            "bigint generated by default as identity primary key")
        line = re.sub(r"\btinyint\b", "smallint", line)
        line = re.sub(r"\s+on update current_timestamp\b", "", line)
        line = re.sub(r"(add column .*?)\s+after\s+\w+", r"\1", line)
        out.append(line)
    return "\n".join(out)

