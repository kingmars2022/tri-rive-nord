"""Write V36: the French guide text with its accents and apostrophes back.

Every migration so far stored the guides' French without accents
("Papiers et cartons souilles d aliments"). This reads the French text of
every guide entry from a database migrated to V35 and writes one update per
changed value, using fr_accents.accent() - a reviewed word list plus context
rules (see that file). Each update names its entry by town and item key and
only applies while the value is still the old text, so an entry an
administrator has since edited is left as they wrote it.

Usage: PGPASSWORD=... python3 generate_v36_french_accents.py <host> <db> <user> > V36__french_guide_accents.sql
"""
import subprocess
import sys

from fr_accents import accent

host, db, user = sys.argv[1:4]


def rows(sql):
    out = subprocess.run(["psql", "-h", host, "-U", user, "-d", db, "-At", "-F", "\x1f", "-R", "\x1e", "-c", sql],
                         check=True, capture_output=True, text=True).stdout
    return [r.split("\x1f") for r in out.split("\x1e") if r]


def q(s):
    return "'" + s.replace("'", "''") + "'"


ITEM = ("(select i.id from sorting_item i join municipality m on m.id = i.municipality_id "
        "where m.slug = {slug} and i.item_key = {key})")

print("-- French guide text with its accents and apostrophes (generated by")
print("-- docs/verification/generate_v36_french_accents.py; do not edit by hand).")
print("-- Each update applies only while the value is still the unaccented original.")
count = 0
for slug, key, *values in rows(
        "select m.slug, i.item_key, t.name, t.instruction, coalesce(t.location, '\x02'), coalesce(t.availability, '\x02') "
        "from sorting_item_translation t join sorting_item i on i.id = t.item_id "
        "join municipality m on m.id = i.municipality_id where t.language_code = 'fr' order by m.slug, i.item_key"):
    for column, old in zip(("name", "instruction", "location", "availability"), values):
        if old == "\x02":
            continue
        new = accent(old)
        if new != old:
            count += 1
            print(f"update sorting_item_translation set {column} = {q(new)}\n"
                  f"where language_code = 'fr' and item_id = {ITEM.format(slug=q(slug), key=q(key))}\n"
                  f"  and {column} = {q(old)};")
for slug, key, position, old in rows(
        "select m.slug, i.item_key, e.position, e.example from sorting_item_example e "
        "join sorting_item i on i.id = e.item_id join municipality m on m.id = i.municipality_id "
        "where e.language_code = 'fr' order by m.slug, i.item_key, e.position"):
    new = accent(old)
    if new != old:
        count += 1
        print(f"update sorting_item_example set example = {q(new)}\n"
              f"where language_code = 'fr' and position = {position} and item_id = {ITEM.format(slug=q(slug), key=q(key))}\n"
              f"  and example = {q(old)};")
print(f"-- {count} values", file=sys.stderr)
