# -*- coding: utf-8 -*-
"""Emits V26: Boisbriand's street-to-sector table, read from the 2025 calendar.

Source: page 6 of "Calendrier des collectes 2025", "Journees et secteurs de
collectes", archived as
data/municipal-sources/boisbriand/2026-11-17/manual_CalendrierCollectes_2025.pdf.
Like V25, this is the 2025 edition, used at the owner's direction because the
2026 one could not be obtained; a street the city moved between sectors or
weekdays for 2026 will be wrong here.

The table is parsed from the PDF's own text layer, by word position, not typed
and not OCR'd: six columns of (street, weekday), sector A above the "SECTEUR B"
banner and sector B below it. Two layout quirks are handled and checked:
  * names that wrap onto a second line, which are always civic-number ranges
    ("Grande-Allee (nos 505 a 1700)"), are joined to the line above;
  * a superscript ("6" + "e" Avenue) can come out as its own line a point
    below its street, and is put back.
It refuses to write anything unless every weekday cell on the page was paired
with exactly one street.

Needs poppler's pdftotext. Run from the repository root:
    python3 docs/verification/generate_v26_boisbriand_streets.py
"""
import html
import io

import pg_sql
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PDF = os.path.join(ROOT, 'data/municipal-sources/boisbriand/2026-11-17/manual_CalendrierCollectes_2025.pdf')
TARGET = os.path.join(ROOT, 'backend/src/main/resources/db/migration/V26__boisbriand_street_directory.sql')
PAGE = 'https://www.ville.boisbriand.qc.ca/services/citoyens/collectes-des-matieres-residuelles'

DAYS = {'Mardi', 'Mercredi', 'Jeudi', 'Vendredi'}
# (street column x, weekday column x) in PDF points, read off the page.
COLUMNS = [(25, 104), (162, 241), (299, 378), (436, 515), (574, 653), (711, 790)]


def page_lines():
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, 'p6.html')
        subprocess.run(['pdftotext', '-f', '6', '-l', '6', '-bbox-layout', PDF, out], check=True)
        text = open(out, encoding='utf-8').read()
    lines = []
    for m in re.finditer(r'<line xMin="([\d.]+)" yMin="([\d.]+)" xMax="([\d.]+)" yMax="([\d.]+)">(.*?)</line>',
                         text, re.S):
        words = re.findall(r'<word[^>]*>(.*?)</word>', m.group(5))
        lines.append((float(m.group(1)), float(m.group(2)), html.unescape(' '.join(words)).strip()))
    return lines


def parse():
    lines = page_lines()
    sector_b = min(y for x, y, t in lines if t.startswith('SECTEUR B'))
    footer = min(y for x, y, t in lines if t.startswith('NOTE') or t.startswith('Industries'))
    entries = []
    for sector, (top, bottom) in (('a', (30, sector_b - 2)), ('b', (sector_b - 2, footer - 2))):
        for name_x, day_x in COLUMNS:
            names = sorted(((y, t) for x, y, t in lines if abs(x - name_x) < 12 and top <= y < bottom),
                           key=lambda r: r[0])
            days = [(y, t) for x, y, t in lines if abs(x - day_x) < 12 and top <= y < bottom and t in DAYS]
            current = None
            for y, t in names:
                if t in ('RUE', 'JOURNÉE') or t.startswith('SECTEUR') or re.fullmatch(r'[A-ZÉÎ]', t):
                    continue  # column headings and the A, B, C... dividers
                if t in ('e', 're', 'er') and current is not None and abs(y - current['y']) < 2.5:
                    current['name'] = re.sub(r'^(\d+) ', lambda m: m.group(1) + t + ' ', current['name'], count=1)
                    continue
                day = [d for dy, d in days if abs(dy - y) < 2.5]
                if day:
                    current = {'sector': sector, 'name': t, 'day': day[0].lower(), 'y': y}
                    entries.append(current)
                elif current is not None and 0 < y - current['y'] < 12:
                    current['name'] += ' ' + t
                    current['y'] = y
                else:
                    sys.exit(f'unplaced text in sector {sector}, column {name_x}: {t!r}')
    for e in entries:
        e['name'] = re.sub(r'^(\d+) (re|e|er) ', r'\1\2 ', e['name'])
        e['name'] = re.sub(r'\(n (os|o) ', lambda m: '(n' + m.group(1) + ' ', e['name'])
        e['name'] = ' '.join(e['name'].split())

    weekday_cells = sum(1 for x, y, t in lines if t in DAYS)
    if len(entries) != weekday_cells:
        sys.exit(f'{len(entries)} streets for {weekday_cells} weekday cells; refusing to write')
    names = [e['name'] for e in entries]
    if len(set(names)) != len(names):
        sys.exit('duplicate street names')
    return entries


def q(s):
    return "'" + s.replace("'", "''") + "'"


def render(entries):
    out = [f"""-- GENERATED by docs/verification/generate_v26_boisbriand_streets.py; edit that, not this.
--
-- Boisbriand's street-to-sector table: which sector V25's "Secteur A, mardi"
-- and so on a resident is in, by street. {len(entries)} rows, parsed from page 6 of
-- the city's 2025 calendar (see the generator for how, and V25 for why 2025).
--
-- A street the city splits by civic number appears once per range, with the
-- range in its name - "Grande-Allee (nos 505 a 1700)" - exactly as printed,
-- because the range is what tells a resident which row is theirs.
--
-- Names keep their accents. Residents type them both ways, and the street
-- search compares without accents or case (see MunicipalityMapper.findStreets).

create table municipality_street (
    id bigint primary key auto_increment,
    municipality_id bigint not null,
    name varchar(200) not null,
    sector_code varchar(40) not null,
    source_url varchar(1000),
    constraint uq_municipality_street unique (municipality_id, name),
    -- A street can only point at a sector its city has. Without this, a typo
    -- in a sector code would hand a resident a sector with no collections,
    -- which the home page would show as an empty week.
    constraint fk_street_sector foreign key (municipality_id, sector_code)
        references municipality_sector (municipality_id, code)
);

set @bb = (select id from municipality where slug = 'boisbriand');

insert into municipality_street (municipality_id, name, sector_code, source_url) values"""]
    rows = [f"(@bb, {q(e['name'])}, '{e['sector']}-{e['day']}', {q(PAGE)})" for e in entries]
    out.append(',\n'.join(rows) + ';\n')
    return '\n'.join(out)


if __name__ == '__main__':
    entries = parse()
    io.open(TARGET, 'w', encoding='utf-8', newline='\n').write(pg_sql.convert(render(entries)))
    print(f'wrote {TARGET}: {len(entries)} streets')
