create table app_user (
    id bigint generated by default as identity primary key,
    email varchar(255) not null unique,
    password_hash varchar(255) not null,
    role varchar(20) not null default 'USER',
    created_at timestamp not null default current_timestamp,
    updated_at timestamp not null default current_timestamp
);

create table user_preference (
    user_id bigint primary key,
    sector varchar(20) not null,
    language_code varchar(10) not null default 'fr',
    reminder_enabled boolean not null default true,
    reminder_time time not null default '20:00:00',
    foreign key (user_id) references app_user(id)
);

create table collection_event (
    id bigint generated by default as identity primary key,
    collection_date date not null,
    sector varchar(20) not null,
    collection_type varchar(40) not null,
    bin_color varchar(20) not null,
    note_fr text,
    note_en text,
    note_zh text,
    source_url varchar(1000),
    created_at timestamp not null default current_timestamp,
    updated_at timestamp not null default current_timestamp
);

create index idx_collection_event_date_sector on collection_event (collection_date, sector);

create table sorting_item (
    id bigint generated by default as identity primary key,
    destination_type varchar(40) not null,
    bin_color varchar(20) not null,
    source_url varchar(1000),
    created_at timestamp not null default current_timestamp,
    updated_at timestamp not null default current_timestamp
);

create table sorting_item_translation (
    id bigint generated by default as identity primary key,
    item_id bigint not null,
    language_code varchar(10) not null,
    name varchar(255) not null,
    instruction text not null,
    foreign key (item_id) references sorting_item(id),
    constraint uq_sorting_item_translation unique (item_id, language_code)
);

create table sorting_item_keyword (
    id bigint generated by default as identity primary key,
    item_id bigint not null,
    language_code varchar(10) not null,
    keyword varchar(255) not null,
    foreign key (item_id) references sorting_item(id)
);

create index idx_sorting_item_keyword on sorting_item_keyword (language_code, keyword);

create table special_notice (
    id bigint generated by default as identity primary key,
    starts_on date not null,
    ends_on date not null,
    title_fr varchar(255) not null,
    title_en varchar(255) not null,
    title_zh varchar(255) not null,
    body_fr text not null,
    body_en text not null,
    body_zh text not null,
    source_url varchar(1000),
    active boolean not null default true
);

-- MySQL's "on update current_timestamp" has no column-level equivalent in
-- PostgreSQL; this trigger function keeps updated_at meaning the same thing.
create function touch_updated_at() returns trigger language plpgsql as $$
begin
    new.updated_at = current_timestamp;
    return new;
end;
$$;

create trigger trg_app_user_updated_at before update on app_user
    for each row execute function touch_updated_at();
create trigger trg_collection_event_updated_at before update on collection_event
    for each row execute function touch_updated_at();
create trigger trg_sorting_item_updated_at before update on sorting_item
    for each row execute function touch_updated_at();
