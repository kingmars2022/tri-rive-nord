-- Full-text search over the sorting guide, for the grounded assistant.
--
-- On MySQL this migration built FULLTEXT indexes: a word parser for French
-- and English, and an ngram parser over generated copies of the text for
-- Chinese. The database moved to PostgreSQL (Aiven retired its free MySQL
-- plan), whose full-text search tokenizes and ranks differently, and has no
-- bigram parser for Chinese.
--
-- Scoring now happens in the application: see SortingSearchIndex. It keeps
-- the two decisions this file used to record -
--
--   * Words for French and English, character bigrams for Chinese. Bigrams on
--     French and English are far too loose: measured on this dataset,
--     "Comment reparer ma voiture ?" (a question the guide cannot answer)
--     scored 4.37 against "Encombrants" purely on incidental bigram overlap.
--     With words the same question scores 0 against every row.
--   * A word that is rare in the guide counts for more than a common one.
--
-- - and fixes one thing MySQL got wrong for this app: word rarity was
-- measured over every city's entries at once, so loading one city reordered
-- another's answers (see V24 and V29). It is now measured within the city.
--
-- Nothing to create: the search reads the same tables everything else does.
